const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const envPath = path.join(__dirname, '..', '.env');

if (fs.existsSync(envPath)) {
    console.log('[setup-env] .env already exists — refusing to overwrite existing secrets.');
    console.log('[setup-env] Delete or back up .env manually if you want to regenerate it.');
    process.exit(0);
}

const jwtSecret = crypto.randomBytes(32).toString('hex');
const shareJwtSecret = crypto.randomBytes(32).toString('hex');
const encryptionKey = crypto.randomBytes(32).toString('hex');
const adminPassword = `SitAdm!${crypto.randomBytes(6).toString('hex')}`;

const content = `# Auto-generated by npm run setup on ${new Date().toISOString()}
PORT=3000
NODE_ENV=development
DEMO_MODE=false
ALLOW_PUBLIC_DEMO=false

JWT_SECRET=${jwtSecret}
SHARE_JWT_SECRET=${shareJwtSecret}
ENCRYPTION_KEY=${encryptionKey}
LEGACY_ENCRYPTION_KEY=med-blockchain-sec-key-32bytes!

BOOTSTRAP_ADMIN_EMAIL=admin@sithospital.org
BOOTSTRAP_ADMIN_PASSWORD=${adminPassword}

# Real Ethereum Sepolia Testnet Connection (optional until deployed)
BLOCKCHAIN_RPC_URL=
BLOCKCHAIN_PRIVATE_KEY=
BLOCKCHAIN_CONTRACT_ADDRESS=
BLOCKCHAIN_NETWORK_NAME=Ethereum Sepolia Testnet
BLOCKCHAIN_EXPLORER_URL=https://sepolia.etherscan.io

CORS_ORIGINS=
TRUST_PROXY=false
AI_EXTERNAL_PROCESSING=false
GEMINI_API_KEY=
`;

fs.writeFileSync(envPath, content, { encoding: 'utf8', mode: 0o600 });

console.log('====================================================================');
console.log(' ✓ Generated secure .env file with fresh 256-bit random secrets!');
console.log('====================================================================');
console.log(' Bootstrap Admin Email    : admin@sithospital.org');
console.log(' Bootstrap Admin Password : (written to .env — inspect .env to view)');
console.log(' Next step: run "npm start" (hardened mode) or "DEMO_MODE=true npm start" (demo mode).');
console.log('====================================================================');
